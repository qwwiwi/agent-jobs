package jobs

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	agentjobs "github.com/qwwiwi/agent-jobs"
)

// The job profile is the owner-rules file of the reference («отдельный файл до 8 КБ, который
// вклеивается в каждый бриф»), generated from the agent's own rules instead of written by hand: the
// agent marks the sections of its instruction files that must hold in every job, and
// `agent-jobs profile --from FILE...` copies exactly those sections into owner_rules_path.
const (
	ProfileBegin = "<!-- agent-jobs:profile -->"
	ProfileEnd   = "<!-- /agent-jobs:profile -->"
	// profileHeader starts every generated profile; a file that starts with it may be regenerated.
	profileHeader = "<!-- agent-jobs job profile, generated by `agent-jobs profile`"
)

// ExtractProfile returns the marked sections of one source file, in order. A file without a marked
// section, an unclosed or nested marker, or an empty section is an error: nothing is guessed.
func ExtractProfile(src string) ([]string, error) {
	var out []string
	rest := src
	for {
		i := strings.Index(rest, ProfileBegin)
		j := strings.Index(rest, ProfileEnd)
		if i < 0 {
			if j >= 0 {
				return nil, errors.New("end marker without a begin marker")
			}
			break
		}
		if j >= 0 && j < i {
			return nil, errors.New("end marker without a begin marker")
		}
		rest = rest[i+len(ProfileBegin):]
		j = strings.Index(rest, ProfileEnd)
		if j < 0 {
			return nil, errors.New("begin marker without an end marker")
		}
		sec := rest[:j]
		if strings.Contains(sec, ProfileBegin) {
			return nil, errors.New("nested begin marker")
		}
		sec = strings.TrimSpace(sec)
		if sec == "" {
			return nil, errors.New("empty marked section")
		}
		out = append(out, sec)
		rest = rest[j+len(ProfileEnd):]
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("no section marked with %s … %s", ProfileBegin, ProfileEnd)
	}
	return out, nil
}

// GenerateProfile builds the job profile from the marked sections of the source files. The result
// is at most MaxOwnerRulesBytes (8 KB, the reference limit), else it is an error and nothing is
// written: a job refuses to start on a larger file anyway.
func GenerateProfile(sources []string) (string, error) {
	if len(sources) == 0 {
		return "", errors.New("at least one --from source is required")
	}
	var names, parts []string
	for _, p := range sources {
		b, err := os.ReadFile(p)
		if err != nil {
			return "", fmt.Errorf("profile source %s: %w", p, err)
		}
		secs, err := ExtractProfile(string(b))
		if err != nil {
			return "", fmt.Errorf("profile source %s: %w", p, err)
		}
		names = append(names, filepath.Base(p))
		parts = append(parts, secs...)
	}
	out := profileHeader + " from " + strings.Join(names, ", ") +
		". Edit the marked sections there and rerun; edits here are overwritten. -->\n\n" +
		strings.Join(parts, "\n\n") + "\n"
	if len(out) > MaxOwnerRulesBytes {
		return "", fmt.Errorf("job profile would be %d bytes, limit is %d: mark less", len(out), MaxOwnerRulesBytes)
	}
	return out, nil
}

// WriteProfile generates the profile and writes it to owner_rules_path (atomically). It replaces a
// missing file, an earlier generated profile or the untouched shipped template; a hand-written
// owner-rules file is replaced only with force.
func (m *Manager) WriteProfile(sources []string, force bool) (string, int, error) {
	out, err := GenerateProfile(sources)
	if err != nil {
		return "", 0, err
	}
	p := m.Cfg.OwnerRulesPath
	if !force {
		cur, err := os.ReadFile(p)
		switch {
		case errors.Is(err, os.ErrNotExist):
		case err != nil:
			return "", 0, fmt.Errorf("owner rules %s: %w", p, err)
		default:
			tpl, _ := agentjobs.Templates.ReadFile("rules/owner.md")
			if !strings.HasPrefix(string(cur), profileHeader) && string(cur) != string(tpl) && strings.TrimSpace(string(cur)) != "" {
				return "", 0, fmt.Errorf("owner rules %s were written by hand; rerun with --force to replace them", p)
			}
		}
	}
	if err := os.MkdirAll(filepath.Dir(p), 0o700); err != nil {
		return "", 0, err
	}
	tmp, err := os.CreateTemp(filepath.Dir(p), ".owner-rules.*")
	if err != nil {
		return "", 0, err
	}
	defer os.Remove(tmp.Name()) //nolint:errcheck // gone after the rename
	if _, err := tmp.WriteString(out); err != nil {
		_ = tmp.Close()
		return "", 0, err
	}
	if err := tmp.Close(); err != nil {
		return "", 0, err
	}
	if err := os.Rename(tmp.Name(), p); err != nil {
		return "", 0, err
	}
	return p, len(out), nil
}
